"""Configure dataset and output paths for SLA-Track."""

import argparse
from pathlib import Path


def write_settings(project, data, output, uavanti=None, a2a=None, dut_images=None, dut_gt=None):
    project, data, output = (Path(p).expanduser().resolve() for p in (project, data, output))
    uavanti = Path(uavanti).expanduser().resolve() if uavanti else data / 'UAV-Anti-UAV'
    a2a = Path(a2a).expanduser().resolve() if a2a else data / 'A2ATracking'
    dut_images = Path(dut_images).expanduser().resolve() if dut_images else data / 'DUT-Anti-UAV/Anti-UAV-Tracking-V0'
    dut_gt = Path(dut_gt).expanduser().resolve() if dut_gt else data / 'DUT-Anti-UAV/Anti-UAV-Tracking-V0GT'
    train = dict(workspace_dir=output, tensorboard_dir=output / 'tensorboard',
                 pretrained_networks=project / 'pretrained', uavanti_dir=uavanti)
    for name, subdir in {
        'lasot': 'lasot', 'got10k': 'got10k/train', 'trackingnet': 'trackingnet',
        'coco': 'coco', 'vasttrack': 'vasttrack', 'imagenet1k': 'imagenet1k',
        'imagenet22k': 'imagenet22k', 'imagenet': 'imagenet', 'tnl2k': 'tnl2k/train',
        'otb99': 'otb_lang', 'depthtrack': 'DepthTrack', 'lasher': 'LasHeR',
        'visevent': 'VisEvent', 'refcoco': 'refcoco', 'lasot_lmdb': 'lasot_lmdb',
        'got10k_lmdb': 'got10k_lmdb', 'trackingnet_lmdb': 'trackingnet_lmdb',
        'coco_lmdb': 'coco_lmdb', 'imagenetvid_lmdb': 'imagenetvid_lmdb',
    }.items():
        train[name + '_dir'] = data / subdir
    train_path = project / 'lib/train/admin/local.py'
    train_text = '"""Local paths generated by tools/setup_paths.py."""\n\nclass EnvironmentSettings:\n    def __init__(self):\n'
    train_text += ''.join('        self.{} = {!r}\n'.format(k, str(v)) for k, v in train.items())
    test = dict(prj_dir=project, save_dir=output, uavanti_path=uavanti,
                a2atracking_path=a2a, dutantiuav_img_path=dut_images, dutantiuav_gt_path=dut_gt,
                results_path=output / 'test/tracking_results',
                segmentation_path=output / 'test/segmentation_results',
                network_path=project / 'pretrained', result_plot_path=output / 'test/result_plots')
    test_path = project / 'lib/test/evaluation/local.py'
    test_text = ('"""Local paths generated by tools/setup_paths.py."""\n'
                 'from lib.test.evaluation.environment import EnvSettings\n\n'
                 'def local_env_settings():\n    settings = EnvSettings()\n')
    test_text += ''.join('    settings.{} = {!r}\n'.format(k, str(v)) for k, v in test.items())
    test_text += '    return settings\n'
    for path, text in [(train_path, train_text), (test_path, test_text)]:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
    return train_path, test_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', required=True, type=Path)
    parser.add_argument('--save-dir', type=Path, default=Path('outputs'))
    parser.add_argument('--uavanti-root', type=Path)
    parser.add_argument('--a2a-root', type=Path)
    parser.add_argument('--dut-images', type=Path)
    parser.add_argument('--dut-gt', type=Path)
    args = parser.parse_args()
    paths = write_settings(Path(__file__).resolve().parents[1], args.data_dir, args.save_dir,
                           args.uavanti_root, args.a2a_root, args.dut_images, args.dut_gt)
    for path in paths:
        print('Configured:', path)


if __name__ == '__main__':
    main()
